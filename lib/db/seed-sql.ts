// SQL generation for supabase/seed.sql. Owner: backend. Used by supabase/scripts/build-seed.ts.
import type { SeedData } from "./sample";

type SqlValue = string | number | boolean | null | readonly string[];

/** SQL literal. standard_conforming_strings is on in Postgres ≥ 9.1, so only single quotes need doubling. */
export function sqlLiteral(v: SqlValue): string {
  if (v === null) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`non-finite number: ${v}`);
    return String(v);
  }
  if (Array.isArray(v)) return v.length ? `array[${v.map((s) => sqlLiteral(s)).join(", ")}]::text[]` : "'{}'::text[]";
  const s = v as string;
  if (s.includes("\u0000")) throw new Error("NUL byte in value");
  return `'${s.replace(/'/g, "''")}'`;
}

function insert<T extends Record<string, SqlValue>>(table: string, rows: readonly T[], conflict: string): string {
  if (rows.length === 0) return `-- ${table}: no rows\n`;
  const cols = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${cols.map((c) => sqlLiteral(r[c] ?? null)).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict ${conflict} do nothing;\n`;
}

export function buildSeedSql(data: SeedData): string {
  return [
    "-- GENERATED by supabase/scripts/build-seed.ts from content/prices.csv, content/help.json and lib/hotlines.ts.",
    "-- Do not edit by hand: change the content files and run `pnpm db:seed`.",
    "begin;",
    "",
    insert("prices", data.prices, "(item_key, area, source, collected_at)"),
    insert("help_contacts", data.contacts, "(category, name_en)"),
    insert("businesses", data.businesses, "(name, area)"),
    "commit;",
    "",
  ].join("\n");
}
